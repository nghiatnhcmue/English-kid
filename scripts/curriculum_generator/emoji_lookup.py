def lookup_emoji(word: str, meaning: str = "") -> str:
    key = word.strip().lower()
    if key in EXPLICIT_EMOJIS:
        return EXPLICIT_EMOJIS[key]

    combined = f"{word} {meaning}".lower()
    for pattern, emo in REGEX_PATTERNS:
        if re.search(pattern, combined):
            return emo

    return "📘"
